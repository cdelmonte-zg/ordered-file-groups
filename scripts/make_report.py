    hashes = (REF / "binaries.sha256").read_text().strip()
    toolchain = (REF / "toolchain.txt").read_text().splitlines()
    patch = (REF / "accept-extra-groups.patch").read_text().strip()
    fd = (REF / "fd-limit/nofile-1024-accept-groups.err").read_text().splitlines()[0]

