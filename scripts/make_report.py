"""Write RESULTS.md from the result files. Run from the repository root:
  python scripts/make_report.py
"""
import csv
import platform
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RESULTS = ROOT / "results"
REF = RESULTS / "round-3-rebuilt"
POOLS = ("128m", "256m", "512m")
NAMES = ["partial-12-depth-1", "partial-12-depth-2", "partial-12-depth-3", "partial-12-depth-4",
         "partial-12-depth-6", "partial-12-depth-12", "sorted-medium-3", "overlap-medium-12",
         "sorted-15-target10", "overlap-1000-x-600"]
MINIMUM = dict(zip(NAMES, [1, 2, 3, 4, 6, 12, 3, 12, 15, 1000]))
ROUNDS = [  # label, directory, tag of the 128 MB runs
    ("round 1, binaries of 2026-09-28, data without fixed time origin", RESULTS / "round-1", "runs"),
    ("round 2, binaries of 2026-09-28, reproducible data", RESULTS / "round-2", "mem-128m"),
    ("round 3, rebuilt binaries, reproducible data", REF, "mem-128m"),
]


def summary(directory, tag):
    path = directory / f"summary-{tag}.tsv"
    if not path.exists():
        return {}
    return {(r["dataset"], r["variant"]): r for r in csv.DictReader(path.open(), delimiter="\t")}


def cell(r):
    if r["ok"].startswith("0/"):
        return f'fails ({r["ok"]})'
    text = f'{r["elapsed_med"]} ({r["elapsed_min"]}..{r["elapsed_max"]})'
    return text if r["ok"] == "10/10" else f'{text}, {r["ok"]} completed'


def times(pool):
    data = summary(REF, f"mem-{pool}")
    rows = ["| dataset | min groups | groups orig / mod | original | modified |",
            "|---|---|---|---|---|"]
    for n in NAMES:
        o, m = data[(n, "original")], data[(n, "accept-groups")]
        rows.append(f'| {n} | {MINIMUM[n]} | {o["groups"] or "-"} / {m["groups"]} '
                    f'| {cell(o)} | {cell(m)} |')
    return "\n".join(rows)


def spills():
    rows = ["| dataset | pool | sort | final aggregate | repartition | RSS MB |",
            "|---|---|---|---|---|---|"]
    show = lambda r, k: r[k] if r[k] != "" else "-"
    for n in NAMES:
        for pool in POOLS:
            data = summary(REF, f"mem-{pool}")
            o, m = data[(n, "original")], data[(n, "accept-groups")]
            rows.append(
                f'| {n} | {pool} | {show(o, "sort_spills")} → {show(m, "sort_spills")} '
                f'| {show(o, "final_agg_spills")} → {show(m, "final_agg_spills")} '
                f'| {show(o, "repartition_spills")} → {show(m, "repartition_spills")} '
                f'| {o["rss_mb_med"]} → {m["rss_mb_med"]} |')
    return "\n".join(rows)


def across_rounds(dataset):
    rows = ["| round | original | modified |", "|---|---|---|"]
    for label, directory, tag in ROUNDS:
        data = summary(directory, tag)
        if (dataset, "original") in data:
            rows.append(f'| {label} | {cell(data[(dataset, "original")])} '
                        f'| {cell(data[(dataset, "accept-groups")])} |')
    return "\n".join(rows)


